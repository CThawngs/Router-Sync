/**
 * packages/cli/src/export/litellm.ts
 *
 * Pure functions buildLiteLLMConfig and renderLiteLLMYaml.
 * Zero network, zero filesystem I/O.
 */

export interface LiteLLMProviderInfo {
  litellmPrefix?: string;
  keyEnv?: string;
  apiBase?: string;
  apiKey?: string;
  [key: string]: unknown;
}

export interface BuildLiteLLMConfigInput {
  combo?: {
    name?: string;
    models?: string[];
    [key: string]: unknown;
  } | null;
  providers?: Record<string, LiteLLMProviderInfo> | null;
  options?: {
    numRetries?: number;
    routingStrategy?: string;
    aliasName?: string;
    [key: string]: unknown;
  } | null;
}

export interface LiteLLMModelItem {
  model_name: string;
  litellm_params: {
    model: string;
    api_key?: string;
    api_base?: string;
  };
}

export interface LiteLLMRouterSettings {
  routing_strategy: string;
  num_retries: number;
  fallbacks?: Array<Record<string, string[]>>;
}

export interface LiteLLMConfigResult {
  model_list: LiteLLMModelItem[];
  router_settings: LiteLLMRouterSettings;
  warnings?: string[];
}

export function buildLiteLLMConfig(input: BuildLiteLLMConfigInput): LiteLLMConfigResult {
  const combo = input?.combo || {};
  const providers = input?.providers || {};
  const options = input?.options || {};

  const warnings: string[] = [];

  const rawAlias = options.aliasName || combo.name || 'combo';
  const hasInvalidChars = !/^[A-Za-z0-9._-]+$/.test(rawAlias);
  if (hasInvalidChars) {
    warnings.push('alias-sanitized');
  }
  const sanitizedAlias = rawAlias.replace(/[^A-Za-z0-9._-]+/g, '-').replace(/^-+|-+$/g, '') || 'combo';

  const rawModels = Array.isArray(combo.models) ? combo.models : [];
  if (rawModels.length === 0) {
    warnings.push('empty-combo');
  }

  const seenModels = new Set<string>();
  const validModelEntries: Array<{ providerId: string; rawModel: string; provInfo: LiteLLMProviderInfo }> = [];

  for (const m of rawModels) {
    if (typeof m !== 'string') continue;
    if (seenModels.has(m)) continue;
    seenModels.add(m);

    const slashIdx = m.indexOf('/');
    if (slashIdx === -1) {
      warnings.push(`unknown-provider:${m}`);
      continue;
    }

    const providerId = m.slice(0, slashIdx);
    const rawModel = m.slice(slashIdx + 1);
    const provInfo = providers[providerId];
    if (!provInfo) {
      warnings.push(`unknown-provider:${providerId}`);
      continue;
    }

    validModelEntries.push({ providerId, rawModel, provInfo });
  }

  const model_list: LiteLLMModelItem[] = [];
  for (let i = 0; i < validModelEntries.length; i++) {
    const entry = validModelEntries[i]!;
    const modelName = i === 0 ? sanitizedAlias : `${sanitizedAlias}-fb${i}`;
    const prefix = entry.provInfo.litellmPrefix || entry.providerId;
    const targetModel = `${prefix}/${entry.rawModel}`;

    const litellm_params: {
      model: string;
      api_key?: string;
      api_base?: string;
    } = {
      model: targetModel,
    };

    if (entry.provInfo.keyEnv) {
      litellm_params.api_key = `os.environ/${entry.provInfo.keyEnv}`;
    }
    if (entry.provInfo.apiBase) {
      litellm_params.api_base = entry.provInfo.apiBase;
    }

    model_list.push({
      model_name: modelName,
      litellm_params,
    });
  }

  const routing_strategy = options.routingStrategy || 'simple-shuffle';
  const num_retries = options.numRetries ?? 2;

  const router_settings: LiteLLMRouterSettings = {
    routing_strategy,
    num_retries,
  };

  if (model_list.length > 1) {
    const fallbackNames = model_list.slice(1).map((m) => m.model_name);
    router_settings.fallbacks = [{ [sanitizedAlias]: fallbackNames }];
  }

  const result: LiteLLMConfigResult = {
    model_list,
    router_settings,
  };

  if (warnings.length > 0) {
    result.warnings = warnings;
  }

  return result;
}

export function renderLiteLLMYaml(config: LiteLLMConfigResult): string {
  const clean: Record<string, unknown> = {
    model_list: config.model_list || [],
    router_settings: config.router_settings || {},
  };
  return `# Generated by RouterSync\n` + JSON.stringify(clean, null, 2) + '\n';
}
